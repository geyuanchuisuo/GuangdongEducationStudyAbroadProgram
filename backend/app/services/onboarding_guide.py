def get_all_sections() -> list[dict]:
    """返回全部章节（引导式流程）。"""
    return ONBOARDING_SECTIONS


def search_guide(keyword: str, limit: int = 5) -> list[dict]:
    """关键词匹配搜索条目。

    命中字段：章节标题/摘要、条目 q/a。简单包含匹配，按命中数排序。
    返回：[{section, q, a}]，最多 limit 条。
    """
    kw = (keyword or "").strip()
    if not kw:
        return []
    # 拆词：按空格切，单个长词也保留整体
    terms = [t for t in kw.replace("？", " ").replace("?", " ").split() if t] or [kw]

    hits: list[tuple[int, dict]] = []
    for sec in ONBOARDING_SECTIONS:
        for item in sec["items"]:
            haystack = f"{sec['title']} {sec['summary']} {item['q']} {item['a']}"
            score = sum(1 for t in terms if t in haystack)
            if score > 0:
                hits.append((score, {"section": sec["title"], "q": item["q"], "a": item["a"]}))
    hits.sort(key=lambda x: x[0], reverse=True)
    return [h for _, h in hits[:limit]]
