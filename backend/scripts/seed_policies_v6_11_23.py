async def main():
    async with async_session_factory() as s:
        existing = set((await s.execute(select(Policy.title))).scalars().all())
        added = 0
        for title, country, category, summary, content, publish_date in POLICIES:
            if title in existing:
                continue
            s.add(Policy(title=title, country=country, category=category,
                         summary=summary, content=content, publish_date=publish_date))
            added += 1
        await s.commit()
    print(f"policies: +{added} added, {len(POLICIES)} total defined (idempotent)")


if __name__ == "__main__":
    asyncio.run(main())
